import re

import markdown as md
from markdown.extensions import Extension as MdExtension
from markdown.postprocessors import Postprocessor as MdPostprocessor


class CodeClassPostprocessor(MdPostprocessor):
    """
    A `Markdown` postprocessor that adds a CSS class
    to all `<code>` tags as per docs requirements.
    """

    def run(self, text: str) -> str:
        """
        Add `linecode` CSS class to `<code>` blocks in HTML.

        Args:
            text (str): The HTML text generated by `Markdown`.

        Returns:
            str: HTML with updated <code> tag class attributes.
        """

        return re.sub(r'<code>(.*?)</code>', r'<code class="linecode">\1</code>', text)


class InlineCodeClassExtension(MdExtension):
    """
    A custom `Markdown` extension that registers the `CodeClassPostprocessor`
    to modify rendered inline code blocks.
    """

    def extendMarkdown(self, md: md.Markdown):
        """
        Register the custom postprocessor with the `Markdown` instance.

        Args:
            md (markdown.Markdown): The `Markdown` parser instance.
        """

        md.postprocessors.register(CodeClassPostprocessor(), 'codeclass', 25)
