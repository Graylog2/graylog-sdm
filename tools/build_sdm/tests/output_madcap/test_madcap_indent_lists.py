import pytest

from output_plugins.madcap_html_output import MadcapHtmlOutput

@pytest.fixture
def plugin():
    return MadcapHtmlOutput()

def test_madcap_markdown_list_indent(plugin):
    '''
    Test the custom indentation filter logic used to format lists after
    the flat list conversion generated by the markdown rendering to HTML.
    '''
    test_list = """
<ul>
<li>Test line 1</li>
<li>Test line 2</li>
</ul>
"""

    result = plugin._indent_list_items(test_list)

    expected = """
<ul>
    <li>Test line 1</li>
    <li>Test line 2</li>
</ul>
"""

    assert result == expected
